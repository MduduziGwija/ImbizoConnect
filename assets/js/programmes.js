// Undergraduate programmes offered by each institution for the 2027 intake.
//
// Each institution has its own catalogue: programme names are the institution's own, and an
// institution only lists what it actually offers (UP has no pharmacy, UCT has no BEd, only UP
// trains vets, universities of technology mostly offer diplomas and BEngTech degrees).
//
//   aps   minimum on the standard 7-point APS scale (Life Orientation excluded). For
//         institutions that score applicants their own way this is our conversion, and `min`
//         shows the institution's own requirement (e.g. "Wits APS 43", "Aggregate 70%").
//   req   minimum percentages: eng, math (Pure/Technical Maths), mathOrLit, sci (Physical
//         Sciences), life (Life Sciences), acc (Accounting).
//   kind  links comparable programmes across institutions (careers, "same programme elsewhere").
//
// SOURCES tells the page where a catalogue came from: 'prospectus' = read from the institution's
// 2027 prospectus in /prospectuses; 'compiled' = compiled from the institution's website and
// published 2027 guides, to be checked against the prospectus.

const P = (inst) => (slug, name, field, aps, req = {}, o = {}) => ({
  id: `${inst}-${slug}`, institution_id: inst, name, field, aps, req,
  qual: o.qual || (/^(Diploma|National Diploma)/.test(name) ? 'diploma' : /^Higher Certificate/.test(name) ? 'hc' : 'degree'),
  years: o.years || (/^Higher Certificate/.test(name) ? 1 : /^Diploma/.test(name) ? 3 : 3),
  kind: o.kind || null, min: o.min || null, note: o.note || null,
});

export const SOURCES = {
  up: 'prospectus', su: 'prospectus', ru: 'prospectus', ul: 'prospectus', wsu: 'prospectus',
};

// Shorthand for common subject requirements.
const E = (eng) => ({ eng });
const EM = (eng, math) => ({ eng, math });
const EMS = (eng, math, sci) => ({ eng, math, sci });
const EML = (eng, mathOrLit) => ({ eng, mathOrLit });
const H = (eng, math, sci, life) => ({ eng, math, ...(sci ? { sci } : {}), ...(life ? { life } : {}) });

const catalogue = {};
const add = (inst, rows) => { const p = P(inst); catalogue[inst] = rows.map((r) => p(...r)); };

