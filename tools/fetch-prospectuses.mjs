#!/usr/bin/env node
/* Downloads every official prospectus PDF listed in assets/js/data.js into
 * /prospectuses and regenerates prospectuses/manifest.js so the site serves
 * the local copy as an attachment.
 *
 *   node tools/fetch-prospectuses.mjs
 *
 * Failed downloads are reported and skipped; the site then falls back to the
 * university's own link. Needs Node 18+ (global fetch). */
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'prospectuses');
const MAX_BYTES = 40 * 1024 * 1024; // keep the repo light; bigger files stay as links

const src = await readFile(join(root, 'assets/js/data.js'), 'utf8');
const ctx = {};
vm.runInNewContext(src + '\nthis.INSTITUTIONS = INSTITUTIONS;', ctx);

await mkdir(outDir, { recursive: true });
let previous = {};
try {
  const m = await readFile(join(outDir, 'manifest.js'), 'utf8');
  previous = JSON.parse(m.slice(m.indexOf('{'), m.lastIndexOf('}') + 1));
} catch { /* first run */ }

const manifest = {};
const failures = [];
for (const inst of ctx.INSTITUTIONS) {
  const p = inst.prospectus;
  if (!p?.pdf) continue;
  const file = `prospectuses/${inst.id}-${p.year}-undergraduate-prospectus.pdf`;
  try {
    const res = await fetch(p.pdf, {
      redirect: 'follow',
      headers: { 'User-Agent': 'Mozilla/5.0 (ImbizoConnect prospectus mirror; +https://github.com/MduduziGwija/ImbizoConnect)' },
      signal: AbortSignal.timeout(120_000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.subarray(0, 5).toString() !== '%PDF-') throw new Error('response is not a PDF');
    if (buf.length > MAX_BYTES) throw new Error(`too large (${(buf.length / 1048576).toFixed(0)} MB)`);
    await writeFile(join(root, file), buf);
    manifest[inst.id] = { file, size: buf.length, source: p.pdf, year: p.year, fetched: new Date().toISOString().slice(0, 10) };
    console.log(`✓ ${inst.short.padEnd(8)} ${(buf.length / 1048576).toFixed(1).padStart(5)} MB  ${file}`);
  } catch (err) {
    // Keep a previously mirrored copy if today's download failed.
    const old = previous[inst.id];
    if (old) {
      try { await stat(join(root, old.file)); manifest[inst.id] = old; } catch { /* file gone */ }
    }
    failures.push(`${inst.short}: ${err.message}`);
    console.warn(`✗ ${inst.short.padEnd(8)} ${err.message}${manifest[inst.id] ? ' (kept previous copy)' : ''}`);
  }
}

await writeFile(join(outDir, 'manifest.js'),
  '/* Generated by tools/fetch-prospectuses.mjs. Do not edit by hand.\n' +
  ' * Maps institution id → locally mirrored prospectus PDF. */\n' +
  `window.PROSPECTUS_LOCAL = ${JSON.stringify(manifest, null, 2)};\n`);

console.log(`\n${Object.keys(manifest).length} prospectuses mirrored, ${failures.length} failed.`);
